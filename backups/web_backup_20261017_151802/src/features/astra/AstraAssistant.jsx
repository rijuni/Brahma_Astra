import React, { useState } from 'react';
import {
  Sparkles,
  Send,
  Code,
  FileCode,
  Layers,
  CheckCircle2,
  AlertCircle,
  Clock,
  ArrowRight
} from 'lucide-react';
import { api } from '../../services/api';

export function AstraAssistant({
  workspaceId,
  activeFile,
  onTaskCreated,
  onSwitchToPatchReview
}) {
  const [instruction, setInstruction] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [error, setError] = useState(null);
  const [chatHistory, setChatHistory] = useState([
    {
      role: 'assistant',
      text: 'Welcome to ASTRA Coding Intelligence. I can inspect open files, plan refactoring tasks, and generate patch proposals for your explicit approval.',
      time: '17:20'
    }
  ]);

  const handleSubmit = async (e) => {
    e?.preventDefault();
    const promptText = instruction.trim();
    if (!promptText || isSubmitting) return;

    setInstruction('');
    setIsSubmitting(true);
    setError(null);

    const time = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });

    // Append user message
    setChatHistory(prev => [
      ...prev,
      { role: 'user', text: promptText, time }
    ]);

    try {
      // Create coding task in ASTRA Engine via backend API
      const task = await api.createCodingTask({
        workspaceId,
        title: promptText.slice(0, 40),
        instruction: activeFile ? `In file ${activeFile.path}: ${promptText}` : promptText
      });

      // Poll task for patch proposal generated by ASTRA Engine
      let finalTask = task;
      for (let i = 0; i < 6; i++) {
        await new Promise(r => setTimeout(r, 1000));
        const polled = await api.getCodingTask(task.id);
        if (polled.patchProposal) {
          finalTask = polled;
          break;
        }
      }

      onTaskCreated(finalTask);

      setChatHistory(prev => [
        ...prev,
        {
          role: 'assistant',
          text: `I have generated a patch proposal: "${finalTask.patchProposal?.summary || promptText}". You can review the diff and approve changes in the Patch Review tab.`,
          time: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          hasPatch: true,
          taskId: finalTask.id
        }
      ]);
    } catch (err) {
      setError(err.message || 'Failed to submit coding instruction to ASTRA Engine.');
      setChatHistory(prev => [
        ...prev,
        {
          role: 'assistant',
          text: `Error dispatching task: ${err.message || 'ASTRA Engine connection failed'}.`,
          time: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          isError: true
        }
      ]);
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div
      style={{
        display: 'flex',
        flexDirection: 'column',
        height: '100%',
        backgroundColor: 'var(--astra-surface)',
        overflow: 'hidden'
      }}
    >
      {/* ── Assistant Header ────────────────────────────────────────── */}
      <div
        style={{
          padding: '12px 16px',
          borderBottom: '1px solid var(--astra-border)',
          backgroundColor: 'var(--astra-panel)',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          flexShrink: 0
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
          <Sparkles size={16} style={{ color: 'var(--astra-electric-blue)' }} />
          <h3 style={{ fontSize: '13px', fontWeight: 600, color: 'var(--astra-text)', margin: 0 }}>
            ASTRA Coding Assistant
          </h3>
        </div>

        {activeFile && (
          <span
            style={{
              fontSize: '11px',
              fontFamily: 'var(--font-code)',
              color: 'var(--astra-cyan)',
              backgroundColor: 'rgba(34, 211, 238, 0.08)',
              padding: '2px 6px',
              borderRadius: 'var(--radius-xs)'
            }}
          >
            {activeFile.path.split('/').pop()}
          </span>
        )}
      </div>

      {/* ── Chat Message Stream ─────────────────────────────────────── */}
      <div
        style={{
          flex: 1,
          overflowY: 'auto',
          padding: '14px',
          display: 'flex',
          flexDirection: 'column',
          gap: '12px'
        }}
      >
        {chatHistory.map((msg, idx) => {
          const isUser = msg.role === 'user';
          return (
            <div
              key={idx}
              style={{
                display: 'flex',
                flexDirection: 'column',
                alignItems: isUser ? 'flex-end' : 'flex-start',
                width: '100%'
              }}
            >
              <div
                style={{
                  maxWidth: '90%',
                  padding: '10px 12px',
                  borderRadius: isUser ? '12px 4px 12px 12px' : '4px 12px 12px 12px',
                  backgroundColor: isUser ? 'rgba(56, 189, 248, 0.12)' : 'var(--astra-panel)',
                  border: isUser ? '1px solid rgba(56, 189, 248, 0.3)' : '1px solid var(--astra-border)',
                  color: msg.isError ? 'var(--status-error)' : 'var(--astra-text)',
                  fontSize: '12px',
                  lineHeight: '1.5'
                }}
              >
                <div>{msg.text}</div>

                {msg.hasPatch && (
                  <button
                    type="button"
                    onClick={() => onSwitchToPatchReview?.(msg.taskId)}
                    style={{
                      marginTop: '8px',
                      display: 'inline-flex',
                      alignItems: 'center',
                      gap: '6px',
                      padding: '4px 10px',
                      borderRadius: 'var(--radius-xs)',
                      backgroundColor: 'var(--astra-violet)',
                      color: '#FFFFFF',
                      fontSize: '11px',
                      fontWeight: 600,
                      border: 'none',
                      cursor: 'pointer'
                    }}
                  >
                    <span>View Diff in Patch Review</span>
                    <ArrowRight size={12} />
                  </button>
                )}

                <div
                  style={{
                    fontSize: '10px',
                    color: 'rgba(167, 174, 194, 0.5)',
                    textAlign: isUser ? 'right' : 'left',
                    marginTop: '4px'
                  }}
                >
                  {msg.time}
                </div>
              </div>
            </div>
          );
        })}

        {isSubmitting && (
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px', color: 'var(--astra-cyan)', fontSize: '12px', padding: '6px 0' }}>
            <Clock size={14} className="spin" />
            <span>ASTRA Engine analyzing syntax and planning patch...</span>
          </div>
        )}
      </div>

      {/* ── Prompt Composer ─────────────────────────────────────────── */}
      <form
        onSubmit={handleSubmit}
        style={{
          padding: '10px 14px',
          borderTop: '1px solid var(--astra-border)',
          backgroundColor: 'var(--astra-panel)',
          display: 'flex',
          flexDirection: 'column',
          gap: '8px',
          flexShrink: 0
        }}
      >
        {error && (
          <div style={{ fontSize: '11px', color: 'var(--status-error)', display: 'flex', alignItems: 'center', gap: '4px' }}>
            <AlertCircle size={12} />
            <span>{error}</span>
          </div>
        )}

        <div style={{ display: 'flex', gap: '8px', alignItems: 'center' }}>
          <input
            type="text"
            placeholder={activeFile ? `Ask about ${activeFile.path}...` : 'Instruct ASTRA code agent...'}
            value={instruction}
            onChange={e => setInstruction(e.target.value)}
            disabled={isSubmitting}
            style={{
              flex: 1,
              padding: '8px 12px',
              fontSize: '12px',
              backgroundColor: 'var(--astra-bg)',
              border: '1px solid var(--astra-border)',
              borderRadius: 'var(--radius-sm)',
              color: 'var(--astra-text)',
              outline: 'none'
            }}
          />

          <button
            type="submit"
            disabled={isSubmitting || !instruction.trim()}
            style={{
              padding: '8px 12px',
              borderRadius: 'var(--radius-sm)',
              backgroundColor: isSubmitting || !instruction.trim() ? 'rgba(56, 189, 248, 0.2)' : 'var(--astra-electric-blue)',
              color: '#070A18',
              border: 'none',
              fontWeight: 700,
              cursor: isSubmitting || !instruction.trim() ? 'not-allowed' : 'pointer',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center'
            }}
            title="Submit instruction (Enter)"
          >
            <Send size={14} />
          </button>
        </div>

        <div style={{ fontSize: '10px', color: 'rgba(167, 174, 194, 0.5)', display: 'flex', justifyContent: 'space-between' }}>
          <span>Powered by ASTRA Engine Port 8002</span>
          <span>Zero automated arbitrary code execution</span>
        </div>
      </form>
    </div>
  );
}
